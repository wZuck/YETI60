#!/usr/bin/env python3
"""Generate and verify the nRF52840 firmware GPIO/ADC/mux contract from XML."""
import argparse,json,re,hashlib
from pathlib import Path
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1];BASE=ROOT/'hardware/ec60-nrf52840';DEST=ROOT/'firmware/yeti60/board_pins.h'
def generate():
    xml=ET.parse(BASE/'netlist.xml').getroot();pinmap=json.loads((BASE/'pinmap.json').read_text())['module_pin_nets']
    module=next(p for p in xml.findall('./libparts/libpart') if p.get('part')=='MDBT50Q-1MV2')
    names={p.get('num'):p.get('name') for p in module.findall('./pins/pin')};netgpio={}
    for pin,net in pinmap.items():
        match=re.fullmatch(r'P(\d)\.(\d+)',names[pin])
        if match:netgpio[net]=32*int(match[1])+int(match[2])
    required=['ROW_DRV'+str(i) for i in range(5)]+['AMUX_SEL_'+str(i) for i in range(3)]+['APLEX_EN_PIN_0','APLEX_EN_PIN_1','APLEX_OUT_PIN_0','ADC','BAT_ADC','BAT_MEAS_EN','AFE_EN','CHG_EN1','CHG_EN2','CHG_CE_N']
    for n in required:
        assert n in netgpio,n
        net=next(nv for nv in xml.findall('./nets/net') if nv.get('name')==n)
        assert any(p.get('ref')=='U1' and pinmap[p.get('pin')]==n for p in net.findall('node'))
    ain={2:0,3:1,4:2,5:3,28:4,29:5,30:6,31:7};assert netgpio['ADC'] in ain and netgpio['BAT_ADC'] in ain
    channels=[]
    for col in range(15):
        net=next(n for n in xml.findall('./nets/net') if n.get('name')=='COL'+str(col));mux='U2' if col<8 else 'U4'
        node=next(n for n in net.findall('node') if n.get('ref')==mux);channels.append(int(re.fullmatch(r'A(\d)_\d+',node.get('pinfunction'))[1]))
    lines=['/* Generated by scripts/generate_yeti60_pin_contract.py; GPIO = port*32+pin. */','#pragma once','#include <stdint.h>','#define YETI_ROWS 5','#define YETI_COLS 15',f'#define YETI_ADC_AIN {ain[netgpio["ADC"]]}',f'#define YETI_BAT_AIN {ain[netgpio["BAT_ADC"]]}']
    for n in required:lines.append(f'#define PIN_{n} {netgpio[n]}')
    for name,vals in [('yeti_rows',[netgpio['ROW_DRV'+str(i)] for i in range(5)]),('yeti_sel',[netgpio['AMUX_SEL_'+str(i)] for i in range(3)]),('yeti_en',[netgpio['APLEX_EN_PIN_'+str(i)] for i in range(2)]),('yeti_channels',channels)]:lines.append('static const uint8_t '+name+'[] = {'+', '.join(map(str,vals))+'};')
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();text=generate()
    if a.check:
        assert DEST.read_text()==text,'Firmware pin contract is stale'
        print('YETI60 GPIO/SAADC/multiplexer contract matches current schematic')
    else:DEST.write_text(text)
